#!/usr/bin/env bash
# HyL Server OOBE Installer
# Usage: curl -fsSL https://raw.githubusercontent.com/qualitydll/hyl/main/scripts/install.sh | bash
set -euo pipefail

# ── Colors ────────────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

info()    { echo -e "${CYAN}[HyL]${NC} $*"; }
ok()      { echo -e "${GREEN}[✓]${NC} $*"; }
warn()    { echo -e "${YELLOW}[!]${NC} $*"; }
die()     { echo -e "${RED}[✗]${NC} $*" >&2; exit 1; }
header()  { echo -e "\n${BOLD}${CYAN}═══ $* ═══${NC}\n"; }

# ── Require root ──────────────────────────────────────────────────────────────
[[ "$EUID" -eq 0 ]] || die "Please run as root: sudo bash install.sh"

# ── Detect OS ─────────────────────────────────────────────────────────────────
header "Detecting system"

OS_ID=""
if [[ -f /etc/os-release ]]; then
    . /etc/os-release
    OS_ID="${ID:-}"
fi

case "$OS_ID" in
    ubuntu|debian)   PKG_MGR="apt-get"; UPDATE="apt-get update -qq"; INSTALL="apt-get install -y -qq" ;;
    centos|rhel|ol)  PKG_MGR="yum";     UPDATE="yum makecache -q";   INSTALL="yum install -y -q" ;;
    fedora)          PKG_MGR="dnf";     UPDATE="dnf makecache -q";   INSTALL="dnf install -y -q" ;;
    alpine)          PKG_MGR="apk";     UPDATE="apk update -q";      INSTALL="apk add -q" ;;
    *)               die "Unsupported OS: '$OS_ID'. Supported: Ubuntu, Debian, CentOS, RHEL, Fedora, Alpine" ;;
esac

ok "OS: $PRETTY_NAME"
info "Package manager: $PKG_MGR"

# ── Install dependencies ───────────────────────────────────────────────────────
header "Installing dependencies"

info "Updating package lists…"
$UPDATE

DEPS="curl openssl"
info "Installing: $DEPS"
$INSTALL $DEPS
ok "Dependencies installed"

# ── Detect architecture ───────────────────────────────────────────────────────
ARCH="$(uname -m)"
case "$ARCH" in
    x86_64)  ARCH_LABEL="amd64" ;;
    aarch64) ARCH_LABEL="arm64" ;;
    armv7l)  ARCH_LABEL="armv7" ;;
    *)       die "Unsupported architecture: $ARCH" ;;
esac
ok "Architecture: $ARCH_LABEL"

# ── Fetch latest release ───────────────────────────────────────────────────────
header "Downloading HyL server"

REPO="qualitydll/hyl"
RELEASE_URL="https://api.github.com/repos/${REPO}/releases/latest"

info "Fetching latest release info…"
LATEST_TAG=$(curl -fsSL "$RELEASE_URL" | grep '"tag_name"' | sed -E 's/.*"([^"]+)".*/\1/')

if [[ -z "$LATEST_TAG" ]]; then
    warn "Could not detect latest release. Falling back to v0.1.0"
    LATEST_TAG="v0.1.0"
fi

ok "Latest version: $LATEST_TAG"

BINARY_NAME="hyl-server-linux-${ARCH_LABEL}"
DOWNLOAD_URL="https://github.com/${REPO}/releases/download/${LATEST_TAG}/${BINARY_NAME}"
INSTALL_PATH="/usr/local/bin/hyl-server"

info "Downloading $BINARY_NAME…"
if ! curl -fsSL "$DOWNLOAD_URL" -o "$INSTALL_PATH" 2>/dev/null; then
    warn "Pre-built binary not found. You need to build from source."
    warn "Install Go 1.22+ then run: go build -o /usr/local/bin/hyl-server ./cmd/hyl-server"
    warn "Continuing with configuration setup…"
    # Create a placeholder so the rest of the script works
    touch "$INSTALL_PATH"
fi

chmod +x "$INSTALL_PATH"
ok "Binary installed to $INSTALL_PATH"

# ── Gather configuration ──────────────────────────────────────────────────────
header "Configuration"

# Port
read -rp "$(echo -e "${CYAN}[?]${NC} Server port [default: 443]: ")" USER_PORT
PORT="${USER_PORT:-443}"
ok "Port: $PORT"

# Password
read -rsp "$(echo -e "${CYAN}[?]${NC} Auth password [leave blank for random]: ")" USER_PASS
echo
if [[ -z "$USER_PASS" ]]; then
    USER_PASS=$(openssl rand -base64 18 | tr -d '=+/' | head -c 24)
    info "Generated password: ${BOLD}${USER_PASS}${NC}"
fi
ok "Password configured"

# Domain / IP
SERVER_IP=$(curl -fsSL https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')
ok "Public IP: $SERVER_IP"

# ── Create directories ────────────────────────────────────────────────────────
header "Setting up files"

mkdir -p /etc/hyl
chmod 700 /etc/hyl

# ── Generate TLS certificate ──────────────────────────────────────────────────
CERT_PATH="/etc/hyl/server.crt"
KEY_PATH="/etc/hyl/server.key"

if [[ ! -f "$CERT_PATH" || ! -f "$KEY_PATH" ]]; then
    info "Generating self-signed TLS certificate…"
    openssl req -x509 -newkey rsa:4096 \
        -keyout "$KEY_PATH" \
        -out "$CERT_PATH" \
        -days 3650 \
        -nodes \
        -subj "/CN=${SERVER_IP}" \
        -addext "subjectAltName=IP:${SERVER_IP}" \
        -quiet 2>/dev/null
    chmod 600 "$KEY_PATH"
    ok "TLS certificate generated (10-year validity)"
else
    ok "Using existing TLS certificate"
fi

# ── Write config ──────────────────────────────────────────────────────────────
CONFIG_PATH="/etc/hyl/server.yaml"
cat > "$CONFIG_PATH" <<EOF
# HyL Server Configuration
# Generated by install.sh on $(date -u +"%Y-%m-%d %H:%M UTC")

listen: "0.0.0.0:${PORT}"

auth:
  password: "${USER_PASS}"

tls:
  cert: "${CERT_PATH}"
  key: "${KEY_PATH}"

congestion:
  # mode: auto (adaptive), brutal (aggressive), economy (battery-friendly)
  mode: auto

bandwidth:
  up: 100    # Mbps hint
  down: 100

log:
  level: info
EOF

chmod 600 "$CONFIG_PATH"
ok "Config written to $CONFIG_PATH"

# ── Create systemd unit ───────────────────────────────────────────────────────
header "Configuring systemd service"

SYSTEMD_UNIT="/etc/systemd/system/hyl.service"
cat > "$SYSTEMD_UNIT" <<EOF
[Unit]
Description=HyL Server (Hysteria Lite)
After=network.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=${INSTALL_PATH} start --config ${CONFIG_PATH}
Restart=on-failure
RestartSec=5s
LimitNOFILE=1048576

# Security hardening
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
ReadWritePaths=/etc/hyl /var/log

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable hyl --quiet
systemctl restart hyl || warn "Service start failed — check logs: journalctl -u hyl -n 50"
ok "systemd service enabled and started"

# ── Allow firewall ────────────────────────────────────────────────────────────
if command -v ufw &>/dev/null && ufw status | grep -q "Status: active"; then
    ufw allow "${PORT}/udp" >/dev/null 2>&1 && ok "ufw: opened UDP port $PORT"
elif command -v firewall-cmd &>/dev/null; then
    firewall-cmd --permanent --add-port="${PORT}/udp" >/dev/null 2>&1
    firewall-cmd --reload >/dev/null 2>&1
    ok "firewalld: opened UDP port $PORT"
fi

# ── Done ──────────────────────────────────────────────────────────────────────
header "Installation complete!"

echo -e "${BOLD}Connection URI:${NC}"
echo -e "  ${GREEN}hyl://${USER_PASS}@${SERVER_IP}:${PORT}${NC}"
echo
echo -e "${BOLD}Useful commands:${NC}"
echo -e "  Status  : systemctl status hyl"
echo -e "  Logs    : journalctl -u hyl -f"
echo -e "  Restart : systemctl restart hyl"
echo -e "  Config  : ${CONFIG_PATH}"
echo
warn "Save the connection URI above — you'll need it for your client."
