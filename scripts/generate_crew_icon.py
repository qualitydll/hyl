from pathlib import Path
from PIL import Image, ImageDraw

target = Path("windows/runner/resources/app_icon.ico")
if not target.exists():
    print("Windows runner icon will be generated by the platform scaffold later.")
    raise SystemExit(0)

sizes = [16, 24, 32, 48, 64, 128, 256]
images = []
for size in sizes:
    scale = 4
    n = size * scale
    image = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    radius = int(n * 0.24)
    draw.rounded_rectangle((0, 0, n - 1, n - 1), radius=radius, fill=(238, 107, 50, 255))
    white = (255, 255, 255, 255)
    center = (n // 2, n // 2)
    hub_r = int(n * 0.105)
    node_r = int(n * 0.065)
    nodes = [
        (int(n * 0.29), int(n * 0.30)),
        (int(n * 0.71), int(n * 0.30)),
        (int(n * 0.29), int(n * 0.70)),
        (int(n * 0.71), int(n * 0.70)),
    ]
    width = max(2, int(n * 0.045))
    for x, y in nodes:
        draw.line((center[0], center[1], x, y), fill=white, width=width)
        draw.ellipse((x-node_r, y-node_r, x+node_r, y+node_r), fill=white)
    draw.ellipse((center[0]-hub_r, center[1]-hub_r, center[0]+hub_r, center[1]+hub_r), fill=white)
    images.append(image.resize((size, size), Image.Resampling.LANCZOS))
images[-1].save(target, format="ICO", sizes=[(s, s) for s in sizes], append_images=images[:-1])
print(f"Generated Crew icon: {target}")
